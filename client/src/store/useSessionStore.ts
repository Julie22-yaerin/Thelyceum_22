/**
 * Session Store — The Lyceum
 *
 * Manages task onboarding sessions:
 *   1. User selects tasks (AI-suggested + custom)
 *   2. Sets timeframes for each task
 *   3. Assigns AI agents by role to serve each task
 *   4. Confirms → workspace starts
 *   5. Human→AI dependency: when human completes a task, the output triggers the AI
 *
 * This is separate from useWorkforceStore (which manages the canvas/graph)
 * and useWorkspaceStore (which manages files/folders).
 */

