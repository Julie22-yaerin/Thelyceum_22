/** Strip client-only fields for server serialization. */
function stripForServer(task: SelectedTask) {
  return {
    id: task.id,
    title: task.title,
    category: task.category,
    description: task.description,
    source: task.source,
    timeframe: task.timeframe,
    estimatedMinutes: task.estimatedMinutes,
    assignedAIs: task.assignedAIs,
    status: task.status,
    order: task.order,
    dependsOn: task.dependsOn,
    humanOutput: task.humanOutput,
    aiOutput: task.aiOutput,
    aiOutputs: task.aiOutputs,
    // Persist clarification questions and answers
    clarificationQuestions: task.clarificationQuestions,
    // Persist retry-limit state
    attemptCount: task.attemptCount,
    error: task.error,
    approvalRequest: task.approvalRequest,
  };
}

function syncSessions(sessions: TaskSession[], current: TaskSession | null): TaskSession[] {
  if (!current) return sessions;
  const idx = sessions.findIndex((s) => s.id === current.id);
  if (idx >= 0) {
    const updated = [...sessions];
    updated[idx] = current;
    return updated;
  }
  return [...sessions, current];
}

